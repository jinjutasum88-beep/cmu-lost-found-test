/* ===================================================================
   ตัววัดผล
   =================================================================== */
export function evaluate(dataset = DATASET, semanticOf = null){
  let tp = 0, fp = 0, tn = 0, fn = 0;
  const errors = [];

  for (const row of dataset){
    const semantic = semanticOf ? semanticOf(row) : null;
    const r = scorePair(row.a, row.b, null, semantic);
    const predicted = !!(r && r.score >= MATCH_THRESHOLD);

    if (predicted && row.label) tp++;
    else if (predicted && !row.label){ fp++; errors.push({ type:"false positive", note:row.note, group:row.group, score:r.score }); }
    else if (!predicted && row.label){ fn++; errors.push({ type:"false negative", note:row.note, group:row.group, score:r ? r.score : 0 }); }
    else tn++;
  }

  const precision = tp + fp ? tp / (tp + fp) : 0;
  const recall = tp + fn ? tp / (tp + fn) : 0;
  const f1 = precision + recall ? 2 * precision * recall / (precision + recall) : 0;
  const accuracy = (tp + tn) / dataset.length;

  return {
    tp, fp, tn, fn, errors,
    precision: Math.round(precision * 1000) / 10,
    recall: Math.round(recall * 1000) / 10,
    f1: Math.round(f1 * 1000) / 10,
    accuracy: Math.round(accuracy * 1000) / 10
  };
}


/* แยกผลตามกลุ่มสถานการณ์ — ดูว่าระบบอ่อนตรงไหน */
export function evaluateByGroup(dataset = DATASET, semanticOf = null){
  const groups = new Map();
  for (const row of dataset){
    const g = row.group || "ทั่วไป";
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(row);
  }
  return [...groups].map(([group, rows]) => ({ group, n: rows.length, ...evaluate(rows, semanticOf) }));
}
